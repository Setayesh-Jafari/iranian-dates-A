const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

export function toFaDigits(value: string): string {
  return value
    .replace(/\d/g, (d) => FA_DIGITS[Number(d)])
    .replace(/\./g, "٫");
}

function faWeight(weight: string): string {
  return toFaDigits(
    weight
      .replace(/\bkg\b/i, "کیلوگرم")
      .replace(/\bml\b/i, "میلی‌لیتر")
      .replace(/\bg\b/i, "گرم")
  );
}

/** Return a product with Persian copy applied (English passes through unchanged). */
export function localizeProduct(product: Product, locale: Locale): Product {
  if (locale !== "fa") return product;

  const tr = FA_PRODUCTS[product.slug];

  return {
    ...product,
    name: tr?.name ?? product.name,
    tagline: tr?.tagline ?? product.tagline,
    description: tr?.description ?? product.description,
    details: tr?.details ?? product.details,
    highlights: tr?.highlights ?? product.highlights,
    origin: FA_ORIGINS[product.origin] ?? product.origin,
    unit: FA_UNITS[product.unit] ?? product.unit,
    weight: faWeight(product.weight),
    badge: product.badge ? (FA_BADGES[product.badge] ?? product.badge) : null,
  };
}

export function localizeProducts(products: Product[], locale: Locale): Product[] {
  return products.map((p) => localizeProduct(p, locale));
}
